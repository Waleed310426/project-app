// lib/providers/user_provider.dart

import 'package:flutter/material.dart';
import 'package:task_ly/models/user_model.dart'; // استيراد نموذج بيانات المستخدم.

/// هذا الكلاس (Provider) هو المسؤول عن تخزين ومشاركة بيانات المستخدم الذي قام بتسجيل الدخول
/// على مستوى التطبيق بأكمله.
/// يستخدم `ChangeNotifier` لإعلام الواجهات (Widgets) عند حدوث أي تغيير في بيانات المستخدم.
class UserProvider extends ChangeNotifier {
  // `_user`: متغير خاص (private) لتخزين كائن المستخدم الحالي.
  // علامة `_` تجعله خاصًا بهذا الملف فقط.
  User? _user;

  // `get user`: دالة "getter" عامة (public) تسمح للواجهات بالوصول إلى بيانات المستخدم
  // للقراءة فقط، دون القدرة على تعديلها مباشرة.
  User? get user => _user;

  /// دالة `setUser`:
  /// تقوم بتحديث بيانات المستخدم الحالي.
  /// تُستدعى عادة بعد نجاح عملية تسجيل الدخول أو عند تحديث بيانات الملف الشخصي.
  void setUser(User? user) {
    _user = user;
    
    // `notifyListeners()`: أهم جزء في `ChangeNotifier`.
    // تقوم هذه الدالة بإرسال إشعار إلى جميع الواجهات التي "تستمع" لهذا الـ Provider،
    // وتخبرها بأن البيانات قد تغيرت، مما يدفعها لإعادة بناء نفسها (rebuild) وعرض البيانات الجديدة.
    notifyListeners();
  }
  
  /// دالة `clearUser`:
  /// تقوم بمسح بيانات المستخدم الحالي (جعلها `null`).
  /// تُستدعى عادة عند قيام المستخدم بتسجيل الخروج.
  void clearUser() {
    _user = null;
    // إعلام الواجهات بأن المستخدم لم يعد موجودًا، مما يسمح بإعادة توجيه المستخدم
    // إلى شاشة تسجيل الدخول على سبيل المثال.
    notifyListeners();
  }
}
